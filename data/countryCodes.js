// MAZ is in Bahrain, so the picker starts there; any country can be chosen.
export const DEFAULT_PHONE_COUNTRY = "BH";

export const findCountry = (iso) => COUNTRY_CODES.find((country) => country.iso === iso) ?? null;

// "AE" → 🇦🇪 (two regional-indicator symbols).
export const flagOf = (iso) =>
  String.fromCodePoint(...[...iso.toUpperCase()].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65));

// Picker options: the form stores the ISO code (+1 / +44 / +7 are shared by several countries); the list shows
// flag, name and dial code — so the search box matches a name ("emirates") or a code ("971", "+44").
export const PHONE_COUNTRY_OPTIONS = COUNTRY_CODES.map((country) => ({
  value: country.iso,
  label: `${flagOf(country.iso)}  ${country.name}  ${country.dial}`,
}));
