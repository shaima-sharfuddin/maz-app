// ⚠️ DEMO — "Download invoice (PDF)" on RequestInvoice (office request invoice) and BillViewer (contract bill). MAZ has no official invoice PDF yet, so the app renders
// the invoice it shows on screen to a PDF on the device (expo-print → cache directory) and opens the share
// sheet (expo-sharing) to save or send it. Replace with the backend's official PDF once it exists.
// The PDF is a printed page, so it uses fixed paper colours (white page, brand navy / crimson) rather than
// the app's light / dark theme.

const A4 = { width: 595, height: 842 }; // points (72 PPI)

const escapeHtml = (value) =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

// Line items → the invoice table + totals. A "VAT" line (real bills carry VAT as a line) moves to the totals box, so
// the table lists only the charges and Subtotal + VAT + Total add up.
function charges(lineItems = [], separateVat = null) {
  const items = lineItems.filter((item) => item.label !== "VAT");
  const vatLine = lineItems.find((item) => item.label === "VAT");
  const vat = typeof separateVat === "number" ? separateVat : vatLine ? vatLine.amount : null;
  const subtotal = items.reduce((sum, item) => sum + (Number(item.amount) || 0), 0);
  return { items: items.map((item) => ({ description: item.label, qty: 1, amount: item.amount })), subtotal, vat };
}

// Everything the PDF (or the text fallback) shows, from fetchRequestStatus's result + the session's Bill To.
function invoiceContent({ requestId, invoice, payment, summary, unit }, billTo) {
  return {
    title: `Invoice ${invoice.number}`,
    number: invoice.number,
    status: payment ? "Paid" : "Unpaid",
    statusKind: payment ? "paid" : "unpaid",
    meta: [
      ["Invoice no.", invoice.number],
      ["Invoice date", formatDate(invoice.issuedOn)],
      payment ? ["Paid on", formatDate(payment.paidDate)] : ["Due date", formatDate(invoice.dueDate)],
      ["Reference", requestId],
    ],
    billTo,
    details: [
      summary?.plan ? ["Service", summary.plan] : null,
      summary?.term ? ["Lease length", summary.term] : null,
      summary?.payment ? ["Payment", summary.payment] : null,
      unit ? ["Unit", unitWithLocation(unit.name, unit.location)] : null,
    ].filter(Boolean),
    ...charges(invoice.lineItems, invoice.vat),
    total: invoice.amount,
    totalLabel: payment ? "Total paid" : "Total due",
    terms: payment
      ? "Paid in full. Thank you for choosing MAZ Business Center."
      : `Payable in full by ${formatDate(invoice.dueDate)}. Pay securely in the MAZ app.`,
    note: summary?.isPlaceholder
      ? "Demo invoice generated by the MAZ app — sample rate and deposit; MAZ confirms final pricing. Not an official tax invoice."
      : "Demo invoice generated by the MAZ app. Not an official tax invoice.",
  };
}

// The same, for a contract bill (fetchBill's result — mock or real API). Only fields the bill carries are shown;
// a bill without a known status (real API, unconfirmed paid field) gets no status stamp.
function billContent(bill, billTo) {
  const badge = paymentBadge(bill.status, bill);
  const STATUS_TEXT = { paid: "Paid", paidDemo: "Paid (demo)", unpaid: "Unpaid" };
  const demo = bill.demoPayment; // ⚠️ DEMO payment from this session (services/mock/demoPaymentLedger.js)
  const period =
    bill.periodStart && bill.periodEnd ? `${formatDate(bill.periodStart)} – ${formatDate(bill.periodEnd)}` : bill.periodLabel;
  const paid = badge === "paid" || badge === "paidDemo";
  return {
    title: `Invoice ${bill.number}`,
    number: bill.number,
    status: badge ? `${STATUS_TEXT[badge]}${bill.statusProvisional ? " (provisional)" : ""}` : null,
    statusKind: badge ? (paid ? "paid" : "unpaid") : null,
    meta: [
      ["Invoice no.", bill.number],
      ["Contract", bill.contractId],
      bill.payment ? ["Paid on", formatDate(bill.payment.paidOn)] : null,
      !bill.payment && bill.dueDate ? ["Due date", formatDate(bill.dueDate)] : null,
      bill.payment?.receipt ? ["Receipt", bill.payment.receipt] : null,
      demo ? ["Paid on (demo)", formatDate(demo.paidDate)] : null,
      demo ? ["Demo receipt", demo.receipt] : null,
    ].filter(Boolean),
    billTo,
    details: [
      period ? ["Billing period", period] : null,
      bill.unit ? ["Unit", unitWithLocation(bill.unit, bill.location)] : null,
    ].filter(Boolean),
    ...charges(bill.lineItems),
    total: bill.total,
    totalLabel: paid ? "Total paid" : "Total due",
    terms: paid
      ? "Thank you for your payment."
      : bill.dueDate
        ? `Payable by ${formatDate(bill.dueDate)}. Pay securely in the MAZ app.`
        : "Pay securely in the MAZ app.",
    note: `Demo invoice generated by the MAZ app from your bill summary. Not an official tax invoice — your official invoice is issued by MAZ Business Center.${
      bill.statusProvisional ? " Payment status is provisional — MAZ confirms payments." : ""
    }${
      demo
        ? " DEMO / TEST: this bill was paid with a demo payment in the app — no money was charged, nothing was sent to MAZ; not an official MAZ receipt."
        : ""
    }`,
  };
}

const money = (amount) => escapeHtml(formatBHD(Number(amount) || 0));
const pairsHtml = (rows) =>
  rows
    .map(([label, value]) => `<div class="pair"><span>${escapeHtml(label)}</span><strong>${escapeHtml(value)}</strong></div>`)
    .join("");

