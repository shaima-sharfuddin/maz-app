// Plain-text version for the share-sheet fallback (no file sharing available, e.g. web).
function invoiceText(content) {
  const block = (rows) => rows.map(([label, value]) => `${label}: ${value}`).join("\n");
  return [
    `MAZ Business Center — ${content.title}${content.status ? ` (${content.status})` : ""}`,
    block(content.meta),
    content.billTo.length ? `Bill to:\n${content.billTo.join("\n")}` : null,
    content.details.length ? block(content.details) : null,
    content.items.map((item) => `${item.description}: ${formatBHD(item.amount)}`).join("\n"),
    [
      `Subtotal: ${formatBHD(content.subtotal)}`,
      typeof content.vat === "number" ? `VAT: ${formatBHD(content.vat)}` : null,
      `${content.totalLabel}: ${formatBHD(content.total)}`,
    ]
      .filter(Boolean)
      .join("\n"),
    content.terms,
    content.note,
  ]
    .filter(Boolean)
    .join("\n\n");
}

// Generates the PDF and opens the share sheet (save to Files / Drive, email, WhatsApp …). Resolves true once
// the sheet has been shown; rejects with an ApiError (for useSubmit + ErrorBanner) if the PDF can't be made.
// Where sharing files isn't available, falls back to sharing the invoice as text.
async function shareInvoice(content) {
  try {
    if (Platform.OS === "web" || !(await Sharing.isAvailableAsync())) {
      await Share.share({ title: content.title, message: invoiceText(content) });
      return true;
    }
    const { uri } = await Print.printToFileAsync({ html: buildInvoiceHtml(content), ...A4 });
    await Sharing.shareAsync(uri, { mimeType: "application/pdf", UTI: "com.adobe.pdf", dialogTitle: content.title });
    return true;
  } catch {
    throw new ApiError("PDF_FAILED", "We couldn't create your invoice PDF. Please try again.");
  }
}

// An office request's first invoice (RequestInvoice): fetchRequestStatus's result + the session's Bill To lines.
export const downloadInvoicePdf = (request, billTo) => shareInvoice(invoiceContent(request, billTo));

// A contract bill (BillViewer): fetchBill's result + the session's Bill To lines.
export const downloadBillPdf = (bill, billTo) => shareInvoice(billContent(bill, billTo));
